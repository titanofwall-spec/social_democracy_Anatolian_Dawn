// Map-mode project validation: three independent textures, preserved appearance, no election changes.
const assert=require('assert');
require('../out/html/data/province-data.js');
const D=require('../out/html/map-design.js');
const doc=D.create(),political=D.layer('Political texture'),physical=D.layer('Physical texture');
const combined=D.layer('Unique combined texture');
doc.layers.push(political,physical,combined);doc.politicalLayerId=political.id;doc.physicalLayerId=physical.id;doc.combinedLayerId=combined.id;
const img=()=>({id:D.id(),type:'image',x:0,y:0,rotation:0,scale:1,opacity:1,provinceId:null,clipProvince:null,width:1675,height:717,name:'map.png',src:'data:image/png;base64,iVBORw0KGgo=',crop:{x:0,y:0,width:1,height:1},lockAspect:true,flipX:false,flipY:false});
political.items.push(img());physical.items.push(img());combined.items.push(img());
political.blend='multiply';political.opacity=.37;physical.blend='overlay';physical.opacity=.65;
physical.clip='sea';political.clip='land';
let v=D.validate(doc);
assert.equal(v.politicalLayerId,political.id);assert.equal(v.physicalLayerId,physical.id);
assert.equal(D.hasTexture(v,'political'),true);assert.equal(D.hasTexture(v,'physical'),true);
assert.equal(D.hasTexture(v,'combined'),true);
assert.equal(v.combinedLayerId,combined.id);
assert.notEqual(v.combinedLayerId,v.politicalLayerId);
assert.notEqual(v.combinedLayerId,v.physicalLayerId);
assert.equal(v.layers[1].blend,'multiply');assert.equal(v.layers[1].opacity,.37);
assert.equal(v.layers[2].clip,'sea');
assert.equal(v.layers[3].id,combined.id);
assert.deepEqual(JSON.parse(D.serialize(doc)),v);
const old=D.create();delete old.politicalLayerId;delete old.combinedLayerId;assert.equal(D.validate(old).politicalLayerId,null);assert.equal(D.validate(old).combinedLayerId,null);
const duplicate=D.clone(doc);duplicate.politicalLayerId=duplicate.physicalLayerId;
assert.throws(()=>D.validate(duplicate),/separate layers/);
const missing=D.clone(doc);missing.politicalLayerId='does-not-exist';
assert.throws(()=>D.validate(missing),/Political map/);
const duplicateCombined=D.clone(doc);duplicateCombined.combinedLayerId=duplicateCombined.politicalLayerId;
assert.throws(()=>D.validate(duplicateCombined),/separate layers/);
const missingCombined=D.clone(doc);missingCombined.combinedLayerId='does-not-exist';
assert.throws(()=>D.validate(missingCombined),/Combined map/);
const withoutCombined=D.clone(doc);withoutCombined.combinedLayerId=null;
assert.equal(D.hasTexture(D.validate(withoutCombined),'combined'),false);
const emptyCombined=D.clone(doc);emptyCombined.layers.find(l=>l.id===emptyCombined.combinedLayerId).items=[];
assert.equal(D.hasTexture(D.validate(emptyCombined),'combined'),false);
assert.equal(D.hasTexture(D.validate(emptyCombined),'political'),true);
console.log('PASS: three independent map-mode textures, dedicated combined layer, backward compatibility, validation');
